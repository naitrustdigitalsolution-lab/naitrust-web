// Local mock integration: room-wide legal consent, access, fees, and minimal UI.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const baseUrl = process.env.NAITRUST_TEST_URL || 'http://localhost:5178';
assert.ok(['localhost', '127.0.0.1'].includes(new URL(baseUrl).hostname));
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.setDefaultTimeout(15000);
const errors = []; page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(baseUrl);
  const result = await page.evaluate(async () => {
    const { appConfig } = await import('/src/configs/env.ts');
    if (!appConfig.isMock) throw new Error('Use mock mode.');
    const { useAuthStore } = await import('/src/libs/store/auth.store.ts');
    const { default: fixtures } = await import('/src/mocks/apis/auth-users.json');
    const { legalApi, legalAdminApi, legalRate, legalFeeMinor, legalFundingBlocked, legalStatus } = await import('/src/features/legal/legal.api.ts');
    const { LEGAL_TERMS_VERSION } = await import('/src/features/legal/terms.ts');
    const { transactionsApi } = await import('/src/libs/api/transactions.api.ts');
    const { dealDetailApi, getLegalRoomDocuments } = await import('/src/libs/api/deal-detail.api.ts');
    const { disputeApi } = await import('/src/libs/api/dispute.api.ts');
    const { patchMockDealRuntime, listMockCreatedDeals, grantMockDealAccess } = await import('/src/libs/api/mock-protected-deal-store.ts');
    const check = (v, m) => { if (!v) throw new Error(m); };
    const rejects = async (fn, message) => { let failed = false; try { await fn(); } catch { failed = true; } check(failed, message); };
    const login = id => { useAuthStore.getState().setUser(fixtures.users.find(u => u.user.id === id).user); useAuthStore.getState().setToken('mock-legal-test'); };
    const approve = (id, version) => legalApi.respond(id, version, 'approve', true, LEGAL_TERMS_VERSION);
    const input = { useCase:'service-repair', workflowMode:'service', dealType:'single', partyMode:'b2b', role:'buyer', participants:[{name:'Emeka',email:'emeka.2fa@naitrust.test'}], title:'Room-wide legal integration', description:'Review room documents', amountMinor:100050, currency:'NGN', deliveryDueDate:'2027-01-01', releaseConditions:'Completed work accepted', expiresInDays:7, agreement:{ version:1,generatedByAi:false,sections:[{heading:'Scope',body:'A demo review.'}] } };
    const selection = { providerId:'biz_mock_legal',purpose:'Review room documents',consent:true,acceptedTermsVersion:LEGAL_TERMS_VERSION,acceptedFee:{rateBps:125,principalMinor:input.amountMinor} };
    const acceptDeal = id => { patchMockDealRuntime(id,{status:'awaiting_funding',invitationStatus:'accepted'}); grantMockDealAccess(id,'usr_mock_004'); };
    login('usr_mock_003');
    check(legalRate()===null,'Rate starts unset'); check(legalFeeMinor(105,1000)===11,'Round half up');
    await rejects(()=>legalAdminApi.setRate(100),'Ordinary user cannot set pricing');
    const before=listMockCreatedDeals().length;
    await rejects(()=>transactionsApi.createTransaction({...input,legalReview:selection}),'Unconfigured rate blocks proposal');
    check(listMockCreatedDeals().length===before,'Failed creation rolled back');
    login('usr_mock_005'); legalAdminApi.setRate(125);
    login('usr_mock_003'); await rejects(()=>transactionsApi.createTransaction({...input,legalReview:{...selection,acceptedTermsVersion:undefined}}),'Terms acceptance required');
    const id=(await transactionsApi.createTransaction({...input,legalReview:selection})).data.id; acceptDeal(id);
    check(legalFundingBlocked(id),'One approval cannot fund');
    await rejects(()=>dealDetailApi.simulateFunding(id),'Funding enforces consent');
    login('usr_mock_004');
    await rejects(()=>legalApi.respond(id,1,'approve',true),'Checkbox alone does not accept terms');
    await rejects(()=>approve(id,99),'Stale proposal rejected'); approve(id,1);
    login('usr_mock_legal'); check(legalApi.assignments().find(a=>a.dealId===id).status==='Awaiting fee payment','Auto assignment');
    await rejects(()=>legalApi.reviewerView(id),'Payment gate remains');
    check((await dealDetailApi.getOne(id)).data===null,'Lawyer has no full room access');
    await rejects(()=>disputeApi.open(id,{reason:'test',description:'test'}),'Lawyer cannot open dispute');
    await rejects(()=>dealDetailApi.addTrackingStep(id,{title:'test'}),'Lawyer cannot alter tracking');
    await rejects(()=>legalAdminApi.accounts(),'Lawyer is not admin');
    login('usr_mock_003'); await dealDetailApi.simulateFunding(id);
    const payment=legalApi.get(id).fee.payment.id;
    legalApi.pay(id); check(legalApi.get(id).fee.payment.id===payment,'No duplicate fee');
    await rejects(()=>legalApi.respond(id,1,'withdraw',true),'One party cannot withdraw active room access');
    await rejects(()=>legalApi.respond(id,1,'decline',true),'Decline cannot bypass joint deactivation');
    await rejects(()=>legalApi.propose(id,{...selection,purpose:'Changed'}),'Cannot replace active appointment unilaterally');
    const pdf='data:application/pdf;base64,'+btoa('%PDF-1.4 Demo invoice');
    await dealDetailApi.addEvidence(id,[{fileName:'invoice.pdf',kind:'Invoice',fileUrl:pdf,mimeType:'application/pdf'}],'Spoofed','seller');
    const evidence=(await dealDetailApi.getOne(id)).data.evidence.find(e=>e.fileName==='invoice.pdf');
    check(evidence.fileUrl.startsWith('mock-evidence:'),'Binary outside localStorage');
    login('usr_mock_legal');
    const view=legalApi.reviewerView(id);
    check(view.documents.some(d=>d.id===evidence.id) && view.documents.some(d=>d.id==='agreement'),'Existing agreement and future upload visible automatically');
    check(view.version===1 && !('parties' in view) && !('funding' in view),'No new consent version or sensitive fields');
    check((await legalApi.document(id,evidence.id,1)).fileUrl.startsWith('data:application/pdf'),'New upload readable without approval');
    await rejects(()=>legalApi.document(id,'another-room-document',1),'Unrelated document blocked');
    legalApi.finding(id,1,'Invoice reviewed.');
    login('usr_mock_003'); check(legalApi.get(id).findings.length===1,'Shared findings');
    legalApi.respond(id,1,'remove',true);
    check(legalStatus(legalApi.get(id))==='Active','First deactivation keeps access');
    await dealDetailApi.addEvidence(id,[{fileName:'later.pdf',kind:'Invoice',fileUrl:pdf,mimeType:'application/pdf'}],'You','buyer');
    login('usr_mock_legal');check(legalApi.reviewerView(id).documents.some(d=>d.name==='later.pdf'),'Uploads still shared while deactivation pending');
    patchMockDealRuntime(id,{status:'completed'});
    check(legalApi.reviewerView(id).documents.length>0,'Retained room access continues after completion');
    login('usr_mock_004');legalApi.respond(id,1,'remove',true);
    login('usr_mock_legal');await rejects(()=>legalApi.reviewerView(id),'Joint deactivation ends access');await rejects(()=>getLegalRoomDocuments(id),'Document adapter also checks access');
    login('usr_mock_003');
    const later=(await transactionsApi.createTransaction({...input,title:'Later appointment'})).data.id; acceptDeal(later);await dealDetailApi.simulateFunding(later);await legalApi.propose(later,selection);
    login('usr_mock_004');approve(later,1);await rejects(()=>legalApi.pay(later),'Only payer pays');
    login('usr_mock_003');legalApi.pay(later);const old=legalApi.get(later);
    // Old selected-document grants are not silently expanded by the new release.
    delete old.sharingScope;old.documents=old.documents.filter(d=>d.id==='agreement');localStorage.setItem(`naitrust:account:usr_mock_003:legal:${later}`,JSON.stringify(old));
    await dealDetailApi.addEvidence(later,[{fileName:'legacy-new.pdf',kind:'Invoice',fileUrl:pdf,mimeType:'application/pdf'}],'You','buyer');
    login('usr_mock_legal');check(!legalApi.reviewerView(later).documents.some(d=>d.name==='legacy-new.pdf'),'Legacy scopes remain limited');
    login('usr_mock_003');await legalApi.propose(later,selection);login('usr_mock_004');approve(later,2);
    login('usr_mock_legal');check(legalApi.reviewerView(later).documents.some(d=>d.name==='legacy-new.pdf'),'Explicit terms upgrade enables ongoing uploads');
    login('usr_mock_005');legalAdminApi.setRate(250);check(legalAdminApi.proposals().find(p=>p.dealId===later).fee.rateBps===125,'Existing fee snapshot retained');
    legalAdminApi.suspend('usr_mock_003',true);login('usr_mock_003');await rejects(()=>legalApi.get(later),'Suspended account blocked');
    login('usr_mock_005');legalAdminApi.suspend('usr_mock_003',false);legalAdminApi.setProvider('biz_mock_legal',false);
    login('usr_mock_legal');await rejects(()=>legalApi.reviewerView(later),'Revocation blocks access');
    login('usr_mock_005');legalAdminApi.setProvider('biz_mock_legal',true);login('usr_mock_legal');await rejects(()=>legalApi.reviewerView(later),'Re-enable does not restore revoked assignment');
    login('usr_mock_001');await rejects(()=>legalApi.get(later),'Unrelated account denied');
    login('usr_mock_legal');useAuthStore.getState().setUser({...useAuthStore.getState().user,role:'business-member'});await rejects(()=>legalApi.assignments(),'Firm staff excluded');
    login('usr_mock_003');return {later};
  });
  console.log('ROOM-WIDE LEGAL API CHECKS PASSED');
  await page.goto(baseUrl+'/app/deals/'+result.later);
  await page.getByRole('button',{name:'Edit legal proposal',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Send legal proposal',exact:true}).isDisabled(),true);
  assert.equal(await page.getByText('Documents to share',{exact:true}).count(),0);
  await page.getByRole('button',{name:'Read legal terms',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Accept legal terms',exact:true}).isDisabled(),true);
  await page.getByRole('dialog').getByRole('checkbox').check();
  await page.getByRole('button',{name:'Accept legal terms',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Send legal proposal',exact:true}).isEnabled(),true);
  await page.getByLabel('Purpose of legal review').fill('A different purpose');
  assert.equal(await page.getByRole('button',{name:'Send legal proposal',exact:true}).isDisabled(),true);
  await page.getByRole('button',{name:'Read legal terms',exact:true}).click();
  assert.equal(await page.getByRole('dialog').getByRole('checkbox').isChecked(),false);
  await page.getByRole('button',{name:'Back',exact:true}).click();
  console.log('TERMS MODAL AND SEND GATE PASSED');
  await page.evaluate(async () => { const { useAuthStore } = await import('/src/libs/store/auth.store.ts'); useAuthStore.getState().reset(); });
  await page.goto(baseUrl+'/');
  await page.getByRole('heading',{name:/An extra pair of eyes\.\s*Right where it matters\./}).waitFor();
  for(const name of ['Kora','QoreID']) {
    const img=page.getByRole('img',{name,exact:true}); await img.scrollIntoViewIfNeeded();
    await img.evaluate(el => el.decode()); assert.ok(await img.evaluate(el=>el.naturalWidth>0),name+' logo loaded');
  }
  assert.equal(await page.getByText('Providus',{exact:false}).count(),0);
  await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Homepage fits mobile');
  assert.deepEqual(errors,[]);
  console.log('HOME FEATURE, OFFICIAL LOGOS AND MOBILE PASSED');
} finally { await browser.close(); }
